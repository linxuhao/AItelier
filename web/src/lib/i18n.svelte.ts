/**
 * Reactive i18n translation module using Svelte 5 $state rune.
 *
 * Uses a module-level $state variable + langStore.subscribe() to make t()
 * reactive: when the user switches language, all consuming components
 * automatically re-render with the new language.
 */

import { get } from 'svelte/store';
import { langStore } from '../stores/i18n';

// ── Types ──

type Lang = 'en' | 'zh-CN' | 'zh-TW' | 'ja' | 'ko' | 'fr' | 'de' | 'es';

// ── Reactive state ──

let currentLang: string = $state(get(langStore));

// Keep the $state variable in sync with the writable store.
// The subscription callback reassigns currentLang within this module,
// so Svelte's compiler wraps it with $.set(), making it reactive.
langStore.subscribe((v: string) => {
  currentLang = v;
});

