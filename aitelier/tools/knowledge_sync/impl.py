"""knowledge_sync — carry review-verified knowledge between DPE runs on a repo.

Runs as a tool STEP near the end of the pipeline (after the final verifier +
deterministic gates, before the final review). It distills already-produced,
review-adjacent artifacts — the architecture design (post architecture-review)
and the final verify report (post final-verifier) — into a single git-IGNORED
file in the project repo:

    <repo>/.aitelier/knowledge.md

The next run's Researcher reads this file (a `from: repository` context source),
so it starts with the prior run's wisdom WITHOUT being handed raw failure
transcripts: only the design summary, what the verifier confirmed works, and the
issues it flagged (explicitly labelled as "known issues / pitfalls").

Design choices that keep this safe and simple:
  - **Git-ignored, not committed.** The file is added to ``.git/info/exclude``
    (the per-clone, untracked ignore list) so it never pollutes the user's repo,
    never shows in diffs/PRs, and `repo_apply`'s ``git add`` skips it. Corrupt
    it? ``rm -rf .aitelier`` — that's the whole recovery story.
  - **Deterministic, no extra LLM call.** Assembled from files already on disk;
    no DeepSeek cost.
  - **One section per project, deduped.** A run rewrites its own section (so the
    goal-loop's repeated passes don't pile up); newest ``_MAX_SECTIONS`` kept.
  - **Fail closed on unsafe legacy tracking.** A recognized generated file can
    be migrated exactly; ambiguous ownership or unrelated work is left intact.
"""

import json
import os
import re
import subprocess
import tempfile
from datetime import date
from pathlib import Path

_KNOWLEDGE_REL = Path(".aitelier") / "knowledge.md"
_EXCLUDE_LINE = ".aitelier/"
_MARKER = "<!-- aitelier:run pid={pid} -->"
_MARKER_RE = re.compile(r"^<!-- aitelier:run pid=(?P<pid>.+?) -->$", re.MULTILINE)
_MAX_SECTIONS = 5
_HEADER = (
    "# AItelier — cross-run knowledge (git-ignored, safe to delete)\n\n"
    "Auto-generated by the DPE pipeline to carry distilled, review-verified\n"
    "knowledge between runs on this repo. NOT committed. Delete freely if stale.\n"
)


def knowledge_sync(*, project_root: str = "", workspace_root: str = "",
                   config_name: str = "", project_id: str = "",
                   out_dir: str = "", **kwargs) -> dict:
    """Distill this run's knowledge into <repo>/.aitelier/knowledge.md.

    Returns {written: bool, path, section, reason/error}. Unsafe legacy
    tracking returns an ``error`` so the tool step stops before a code claim.
    """
    try:
        repo = Path(project_root).resolve() if project_root else None
        if not repo or not repo.exists():
            return {"written": False, "reason": f"repo not found: {project_root}"}

        pid = project_id or (Path(workspace_root).name if workspace_root else "run")
        graph_dir = _locate_graph_dir(workspace_root, config_name, out_dir)

        section = _build_section(pid, graph_dir)
        if section is None:
            return {"written": False,
                    "reason": "no distillable artifacts (design/verify) found"}

        kpath = repo / _KNOWLEDGE_REL
        existing = kpath.read_text(encoding="utf-8", errors="replace") \
            if kpath.exists() else ""
        merged = _merge(existing, pid, section).encode("utf-8")

        # Establish and verify the effective exclude before changing knowledge.
        try:
            _ensure_excluded(repo)
        except Exception as exc:
            tracked = _git(repo, "ls-files", "--error-unmatch", "--",
                           _KNOWLEDGE_REL.as_posix())
            if tracked.returncode == 0:
                return _migration_refusal(
                    owner="unproven",
                    reason=f"the effective Git exclude is unavailable ({exc})")
            return _untracked_refusal(
                reason=f"the effective Git exclude is unavailable ({exc})")
        try:
            migration = _migrate_tracked_knowledge(repo, merged)
        except Exception as exc:
            return _migration_refusal(
                owner="unproven", reason=f"migration check failed ({exc})")
        if isinstance(migration, dict):
            return migration

        if migration is None:
            refusal = _write_untracked_knowledge(repo, kpath, merged)
            if refusal is not None:
                return refusal
        result = {"written": True, "path": str(kpath), "section": pid}
        if migration:
            result["migration"] = migration
        return result
    except Exception as e:
        return {"written": False, "error": f"knowledge_sync failed closed: {e}"}


# ── Distillation ──────────────────────────────────────────────────────────

def _locate_graph_dir(workspace_root: str, config_name: str,
                      out_dir: str) -> Path | None:
    """Directory holding the per-step output dirs (sibling '2', '5', ...).

    out_dir ($STEP_DIR) is the reliable source: skillflow injects it for tool
    steps but does NOT inject workspace_root (it stays ""), so its parent is the
    graph dir. workspace_root/config_name is only a fallback for callers that
    pass it explicitly.
    """
    if out_dir:  # $STEP_DIR → parent is the graph dir
        p = Path(out_dir).parent
        if p.exists():
            return p
    if workspace_root and config_name:
        d = Path(workspace_root) / config_name
        if d.exists():
            return d
    return None


def _build_section(pid: str, graph_dir: Path | None) -> str | None:
    """Assemble one markdown section from design + verify artifacts.

    Returns None if neither artifact is present (nothing worth recording).
    """
    if graph_dir is None:
        return None

    design = _read_text(graph_dir / "2" / "step2_design.md")
    report = _read_json(graph_dir / "5" / "final" / "verify_report.json")
    if not design and not report:
        return None

    lines = [_MARKER.format(pid=pid), f"## {pid} — {date.today().isoformat()}", ""]

    if report:
        met = report.get("all_goals_met")
        deploy = report.get("ready_for_deploy")
        lines.append(f"**Outcome:** goals_met={_b(met)} · ready_for_deploy={_b(deploy)}")
        verified = [str(s) for s in (report.get("verified_subtasks") or [])]
        if verified:
            lines.append(f"**Verified working:** {', '.join(verified)}")
        issues = [str(s) for s in (report.get("issues") or [])]
        if issues:
            lines.append("")
            lines.append("**Known issues / pitfalls (final review — avoid repeating):**")
            lines.extend(f"- {i}" for i in issues)

    if design:
        lines.append("")
        lines.append("**Architecture (from approved design):**")
        lines.append(_design_summary(design))

    return "\n".join(lines).rstrip() + "\n"


def _design_summary(design: str, max_chars: int = 1400) -> str:
    """Overview paragraph (if any) + the design's section headers."""
    overview = _section_body(design, "Overview")
    headers = [m.group(2).strip()
               for m in re.finditer(r"^(#{2,3})\s+(.*)$", design, re.MULTILINE)]
    parts = []
    if overview:
        parts.append(overview.strip())
    if headers:
        parts.append("Sections: " + " · ".join(headers[:20]))
    text = "\n\n".join(parts).strip()
    if len(text) > max_chars:
        text = text[:max_chars].rstrip() + " …"
    return text or "(see step2_design.md)"


def _section_body(md: str, header: str) -> str:
    """Body text under a `## header` up to the next same/higher header."""
    m = re.search(rf"^#{{1,3}}\s+{re.escape(header)}\s*$", md, re.MULTILINE)
    if not m:
        return ""
    start = m.end()
    nxt = re.search(r"^#{1,3}\s+", md[start:], re.MULTILINE)
    body = md[start: start + nxt.start()] if nxt else md[start:]
    return body.strip()


# ── Merge / dedup ─────────────────────────────────────────────────────────

def _merge(existing: str, pid: str, section: str) -> str:
    """Drop any prior section for `pid`, prepend the new one, cap to N."""
    sections = _split_sections(existing)
    sections = [(p, body) for (p, body) in sections if p != pid]
    sections.insert(0, (pid, section))
    sections = sections[:_MAX_SECTIONS]
    body = "\n\n".join(s for _, s in sections).rstrip() + "\n"
    return _HEADER + "\n" + body


def _split_sections(text: str) -> list[tuple[str, str]]:
    """Split a knowledge file into (pid, section_text) by run markers."""
    if not text:
        return []
    matches = list(_MARKER_RE.finditer(text))
    out = []
    for i, m in enumerate(matches):
        start = m.start()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        out.append((m.group("pid"), text[start:end].strip()))
    return out


# ── Git ignore wiring ─────────────────────────────────────────────────────


def _git(repo: Path, *args: str,
         env: dict | None = None) -> subprocess.CompletedProcess:
    command = ["git", *args]
    try:
        return subprocess.run(
            command, cwd=repo, capture_output=True, text=True,
            errors="replace", check=False, timeout=60,
            env=({**os.environ, **env} if env else None))
    except (OSError, subprocess.TimeoutExpired) as exc:
        return subprocess.CompletedProcess(command, 128, "", str(exc))


def _migration_refusal(*, owner: str, reason: str,
                       recovery_action: str | None = None) -> dict:
    path = _KNOWLEDGE_REL.as_posix()
    action = recovery_action or (
        f"Back up and review {path}; make the worktree clean without altering "
        f"it, run `git rm --cached -- {path}`, verify that this is the only "
        "staged path, then run `git commit -m "
        "'AItelier: untrack generated knowledge'` and rerun knowledge_sync.")
    return {
        "written": False,
        "error": (f"tracked {path} cannot be migrated safely: {reason}; "
                  f"owner={owner}. Recovery: {action}"),
        "tracked_path": path,
        "owner": owner,
        "recovery_action": action,
    }


def _untracked_refusal(*, reason: str) -> dict:
    path = _KNOWLEDGE_REL.as_posix()
    action = (
        "Run `git rev-parse --git-common-dir`, ensure its `info/exclude` "
        f"contains `{_EXCLUDE_LINE}`, then verify `git check-ignore -- {path}` "
        f"and `git status --porcelain=v1 --untracked-files=all -- {path}` "
        "before rerunning knowledge_sync.")
    return {
        "written": False,
        "error": (f"untracked {path} cannot be handed off safely: {reason}; "
                  f"owner=untracked. Recovery: {action}"),
        "tracked_path": path,
        "owner": "untracked",
        "recovery_action": action,
    }


def _atomic_write(path: Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, raw_tmp = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    tmp = Path(raw_tmp)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def _restore_knowledge(path: Path, *, existed: bool, content: bytes) -> bool:
    try:
        if existed:
            _atomic_write(path, content)
        else:
            path.unlink(missing_ok=True)
            try:
                path.parent.rmdir()
            except OSError:
                pass
        return path.read_bytes() == content if existed else not path.exists()
    except OSError:
        return False


def _safe_unlink(path: Path) -> None:
    try:
        path.unlink(missing_ok=True)
    except OSError:
        pass


def _write_untracked_knowledge(repo: Path, kpath: Path,
                               content: bytes) -> dict | None:
    """Write an untracked file and roll it back unless Git proves it ignored."""
    existed = kpath.exists()
    try:
        before = kpath.read_bytes() if existed else b""
    except OSError as exc:
        return _untracked_refusal(reason=f"existing knowledge is unreadable ({exc})")
    if kpath.is_symlink() or (existed and not kpath.is_file()):
        return _untracked_refusal(reason="the knowledge path is not a regular file")
    pre_status = _git(repo, "status", "--porcelain=v1", "--untracked-files=all",
                      "--", _KNOWLEDGE_REL.as_posix())
    if pre_status.returncode or pre_status.stdout:
        return _untracked_refusal(
            reason="the exact path's clean untracked state is unavailable")
    try:
        _atomic_write(kpath, content)
    except OSError as exc:
        return _untracked_refusal(reason=f"the knowledge write failed ({exc})")
    ignored = _git(repo, "check-ignore", "--quiet", "--",
                   _KNOWLEDGE_REL.as_posix())
    final_status = _git(repo, "status", "--porcelain=v1", "--untracked-files=all",
                        "--", _KNOWLEDGE_REL.as_posix())
    if ignored.returncode or final_status.returncode or final_status.stdout:
        restored = _restore_knowledge(kpath, existed=existed, content=before)
        detail = ("knowledge bytes were restored" if restored
                  else "knowledge-byte rollback could not be verified")
        return _untracked_refusal(
            reason=f"the clean ignored handoff could not be verified; {detail}")
    return None


def _migrate_tracked_knowledge(repo: Path,
                               replacement: bytes) -> str | dict | None:
    """Commit removal of the exact generated path from Git tracking, or refuse.

    The working file is preserved byte-for-byte. Migration is allowed only when
    both HEAD and the working copy carry AItelier's generated header, the exact
    path has no staged changes, and no other working-tree change exists.
    """
    rel = _KNOWLEDGE_REL.as_posix()
    tracked = _git(repo, "ls-files", "--error-unmatch", "--", rel)
    if tracked.returncode == 1:
        return None
    if tracked.returncode != 0:
        return _migration_refusal(
            owner="unproven", reason="Git could not establish whether the path is tracked")

    kpath = repo / _KNOWLEDGE_REL
    try:
        working = kpath.read_bytes()
    except OSError as exc:
        return _migration_refusal(
            owner="unproven", reason=f"the tracked working file is unreadable ({exc})")
    head = _git(repo, "show", f"HEAD:{rel}")
    marker = _HEADER.encode("utf-8")
    working_owned = working.startswith(marker) and bool(_MARKER_RE.search(
        working.decode("utf-8", errors="replace")))
    head_owned = head.returncode == 0 and head.stdout.startswith(_HEADER) \
        and bool(_MARKER_RE.search(head.stdout))
    owner = ("aitelier-generated" if working_owned and head_owned
             and kpath.is_file() and not kpath.is_symlink() else "unproven")
    if owner != "aitelier-generated":
        return _migration_refusal(
            owner=owner, reason="AItelier ownership is not proven in HEAD and the working file")

    full = _git(repo, "status", "--porcelain=v1", "-z", "--untracked-files=all")
    scoped = _git(repo, "status", "--porcelain=v1", "-z", "--untracked-files=all",
                  "--", rel)
    if full.returncode or scoped.returncode:
        return _migration_refusal(owner=owner, reason="Git status is unavailable")
    if full.stdout != scoped.stdout:
        return _migration_refusal(owner=owner, reason="unrelated working-tree changes are present")
    staged = _git(repo, "diff", "--cached", "--quiet", "--", rel)
    if staged.returncode != 0:
        reason = ("the exact path has staged changes" if staged.returncode == 1
                  else "the exact path's staged state is unavailable")
        return _migration_refusal(owner=owner, reason=reason)
    ignored = _git(repo, "check-ignore", "--no-index", "--quiet", "--", rel)
    if ignored.returncode != 0:
        return _migration_refusal(owner=owner, reason="the effective Git exclude is unavailable")

    before_head = _git(repo, "rev-parse", "HEAD")
    if before_head.returncode or not before_head.stdout.strip():
        return _migration_refusal(owner=owner, reason="repository HEAD is unavailable")
    index_result = _git(repo, "rev-parse", "--git-path", "index")
    if index_result.returncode or not index_result.stdout.strip():
        return _migration_refusal(
            owner=owner, reason="repository index path is unavailable")
    index_path = Path(index_result.stdout.strip())
    if not index_path.is_absolute():
        index_path = (repo / index_path).resolve()
    temp_index = None
    lock_path = index_path.with_name(index_path.name + ".lock")
    lock_fd = None
    lock_identity = None
    knowledge_changed = False
    try:
        index_before = index_path.read_bytes()
        index_mode = index_path.stat().st_mode & 0o777
        fd, raw_index = tempfile.mkstemp(
            prefix="index.aitelier-", dir=index_path.parent)
        os.close(fd)
        temp_index = Path(raw_index)
        temp_index.write_bytes(index_before)
        _atomic_write(kpath, replacement)
        knowledge_changed = True

        temp_env = {"GIT_INDEX_FILE": str(temp_index)}
        removed = _git(repo, "rm", "--cached", "--quiet", "--", rel,
                       env=temp_env)
        if removed.returncode:
            raise RuntimeError("Git refused exact-path index removal")
        tree = _git(repo, "write-tree", env=temp_env)
        if tree.returncode or not tree.stdout.strip():
            raise RuntimeError("Git could not write the exact migration tree")
        committed = _git(
            repo, "commit-tree", tree.stdout.strip(), "-p",
            before_head.stdout.strip(), "-m",
            "AItelier: untrack generated knowledge")
        if committed.returncode or not committed.stdout.strip():
            detail = (committed.stderr or committed.stdout).strip()[:200]
            raise RuntimeError(
                f"Git could not create the exact migration commit ({detail})")

        commit = committed.stdout.strip()
        parent = _git(repo, "rev-parse", f"{commit}^")
        names = _git(repo, "diff-tree", "--no-commit-id", "--name-status", "-r",
                     before_head.stdout.strip(), commit)
        omitted = _git(repo, "ls-tree", "-r", "--name-only", commit, "--", rel)
        if (parent.returncode
                or parent.stdout.strip() != before_head.stdout.strip()
                or names.returncode
                or names.stdout.splitlines() != [f"D\t{rel}"]
                or omitted.returncode or omitted.stdout
                or kpath.read_bytes() != replacement):
            raise RuntimeError(
                "prospective migration exactness could not be verified")
        if index_path.read_bytes() != index_before:
            raise RuntimeError("repository index changed while migration was prepared")
        lock_fd = os.open(
            lock_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        lock_stat = os.fstat(lock_fd)
        lock_identity = (lock_stat.st_dev, lock_stat.st_ino)
        os.fchmod(lock_fd, index_mode)
        with os.fdopen(lock_fd, "wb") as lock_handle:
            lock_fd = None
            lock_handle.write(temp_index.read_bytes())
            lock_handle.flush()
            os.fsync(lock_handle.fileno())
        lock_fd = None
        if index_path.read_bytes() != index_before:
            raise RuntimeError("repository index changed while migration lock was held")
        updated = _git(repo, "update-ref", "HEAD", commit,
                       before_head.stdout.strip())
        if updated.returncode:
            raise RuntimeError("repository HEAD changed while migration was prepared")
        try:
            os.replace(lock_path, index_path)
            lock_identity = None
        except OSError as exc:
            rolled_back = _git(repo, "update-ref", "HEAD",
                               before_head.stdout.strip(), commit)
            restored = _restore_knowledge(kpath, existed=True, content=working)
            current = _git(repo, "rev-parse", "HEAD")
            if rolled_back.returncode == 0 and restored:
                knowledge_changed = False
                raise RuntimeError(
                    f"index publication failed and was rolled back exactly ({exc})")
            actual = (current.stdout.strip()
                      if current.returncode == 0 else "unavailable")
            action = (
                f"Stop and inspect HEAD={actual}, expected prior HEAD="
                f"{before_head.stdout.strip()}, and `{index_path}`; do not run "
                "an automatic git rm until the ref/index pair is reconciled.")
            return _migration_refusal(
                owner=owner,
                reason="migration publication failed and exact rollback could "
                "not be verified",
                recovery_action=action)
        return "untracked_generated_knowledge"
    except (OSError, RuntimeError) as exc:
        restored = (not knowledge_changed or _restore_knowledge(
            kpath, existed=True, content=working))
        return _migration_refusal(
            owner=owner, reason=f"migration publication refused ({exc}); "
            f"knowledge bytes restored={str(restored).lower()}")
    finally:
        if lock_fd is not None:
            try:
                os.close(lock_fd)
            except OSError:
                pass
        if lock_identity is not None:
            try:
                lock_stat = lock_path.stat()
                if (lock_stat.st_dev, lock_stat.st_ino) == lock_identity:
                    _safe_unlink(lock_path)
            except OSError:
                pass
        if temp_index is not None:
            _safe_unlink(temp_index)


def _ensure_excluded(repo: Path) -> None:
    """Append `.aitelier/` to .git/info/exclude (untracked, per-clone) once.

    Uses .git/info/exclude rather than the tracked .gitignore so we never modify
    a file the user owns / that shows up in their diff.
    """
    # Git reads info/exclude from the *common* git directory. In a linked
    # worktree, ``.git`` points at ``<common>/worktrees/<name>``; writing an
    # ``info/exclude`` below that administrative directory has no effect and
    # leaves the generated knowledge file dirty. Ask Git for the authoritative
    # path instead of parsing its implementation-specific .git file ourselves.
    resolved = _git(repo, "rev-parse", "--git-common-dir")
    if resolved.returncode != 0 or not resolved.stdout.strip():
        raise RuntimeError("Git could not resolve its common directory")
    git_dir = Path(resolved.stdout.strip())
    if not git_dir.is_absolute():
        git_dir = (repo / git_dir).resolve()
    info = git_dir / "info"
    info.mkdir(parents=True, exist_ok=True)
    exclude = info / "exclude"
    current = exclude.read_text(encoding="utf-8") if exclude.exists() else ""
    if any(ln.strip() == _EXCLUDE_LINE for ln in current.splitlines()):
        pass
    else:
        sep = "" if current.endswith("\n") or not current else "\n"
        exclude.write_text(
            current + sep + f"{_EXCLUDE_LINE}\n", encoding="utf-8")
    ignored = _git(repo, "check-ignore", "--no-index", "--quiet", "--",
                   _KNOWLEDGE_REL.as_posix())
    if ignored.returncode:
        raise RuntimeError("Git did not confirm the effective exclude")


# ── small helpers ─────────────────────────────────────────────────────────

def _read_text(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""
    except Exception:
        return ""


def _read_json(p: Path) -> dict | None:
    try:
        return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None
    except Exception:
        return None


def _b(v) -> str:
    return "true" if v is True else "false" if v is False else "unknown"
