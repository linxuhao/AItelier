/**
 * Reactive i18n translation module using Svelte 5 $state rune.
 *
 * Uses a module-level $state variable + langStore.subscribe() to make t()
 * reactive: when the user switches language, all consuming components
 * automatically re-render with the new language.
 */

import { get } from 'svelte/store';
import { langStore } from '../stores/i18n';

// ── Types ──

